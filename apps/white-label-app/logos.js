// Anything without a mark falls back to a lettered tile, so the grid never breaks.
export const hasLogo = (p) => !!P[p];
export const brandColor = (p) => P[p]?.color || '#444343';

// Google Ads carries its own fills; everything else inherits currentColor.
const MULTICOLOUR = new Set(['googleads']);

export const logo = (platform, size = 22) => {
  const spec = P[platform];
  if (!spec)
    return `<span class="logo-fallback" style="width:${size}px;height:${size}px"
      aria-hidden="true">${(platform || '?')[0].toUpperCase()}</span>`;
  return `<svg width="${size}" height="${size}" viewBox="0 0 24 24"
    fill="${MULTICOLOUR.has(platform) ? 'none' : 'currentColor'}"
    aria-hidden="true" focusable="false">${spec.path}</svg>`;
};
